// A stored, AI-generated text (an investigation summary or a reading of a ranking, #28) with its
// citations, sources and review state. Sentences tied to a cited NASA source read like the
// Assistant's answers: white and underlined with a numbered citation; the assistant's own words are
// lighter. AI use: written with Claude Code (Claude Opus 5.5), reviewed by the team.
import { Fragment, useMemo, useRef } from 'react'
import { ExternalLink, FileText, TriangleAlert, UserCheck } from 'lucide-react'
import { formatDate } from '../catalogue.js'
import './AiSummary.css'

// Paragraphs from the blocks. A block may end one paragraph and start the next; punctuation that
// opens an uncited piece belongs to the cited sentence before it (as on the Assistant page).
function paragraphs(blocks) {
  const out = [[]]
  blocks.forEach((block, b) => {
    block.text.split(/\n{2,}/).forEach((piece, k) => {
      if (k > 0) out.push([])
      if (piece) out[out.length - 1].push({ ...block, text: piece, key: `${b}-${k}` })
    })
  })
  for (const para of out)
    for (let i = 1; i < para.length; i++) {
      const lead = para[i].text.match(/^[.,;:!?)]+/)
      if (lead && para[i - 1].kind === 'source') {
        para[i - 1] = { ...para[i - 1], text: para[i - 1].text + lead[0] }
        para[i] = { ...para[i], text: para[i].text.slice(lead[0].length) }
      }
    }
  return out.map((p) => p.filter((piece) => piece.text)).filter((p) => p.length > 0)
}

const KIND = { ranking: 'FLARE ranking', record: 'PSI record' }

function Source({ source, n, id, quotes }) {
  const where = KIND[source.kind] ?? (source.page ? `Document, page ${source.page}` : 'Document')
  return (
    <li id={`${id}-src-${n}`} className="ai-source">
      <span className="ai-source-n">{n}</span>
      <div className="ai-source-body">
        <p className="ai-source-head">
          <strong>{source.kind === 'ranking' ? source.title : source.label}</strong>
          <span className="ai-source-kind">{where}</span>
          {source.kind !== 'ranking' && (
            <a href={source.url} target="_blank" rel="noreferrer" className="ai-source-link">
              <span className="id">{source.kind === 'record' ? source.accession : source.file_name}</span>
              <ExternalLink size={14} aria-hidden="true" />
              <span className="visually-hidden">
                {source.kind === 'record' ? ' (NASA PSI page' : ' (download from NASA PSI'}, opens in a new tab)
              </span>
            </a>
          )}
        </p>
        {quotes.length > 0 && (
          <ul className="ai-quotes" aria-label="Words the text cites">
            {quotes.map((quote, j) => (
              <li key={j}>“{quote.trim()}”</li>
            ))}
          </ul>
        )}
        <details className="ai-full">
          <summary>
            <FileText size={14} aria-hidden="true" />
            {source.kind === 'document' ? 'Whole passage' : `${KIND[source.kind]} text FLARE sent`}
          </summary>
          <p>{source.text}</p>
        </details>
      </div>
    </li>
  )
}

// `data` is a stored summary or reading: { model, generated, reviewed, reviewed_by, blocks, sources }.
export default function AiSummary({ id, title, intro, data }) {
  const register = useRef(null)
  const index = useMemo(() => Object.fromEntries(data.sources.map((s, i) => [s.id, i + 1])), [data])
  const quotes = useMemo(() => {
    const q = {}
    for (const block of data.blocks)
      for (const c of block.citations ?? []) (q[c.source_id] ??= []).includes(c.cited_text) || q[c.source_id].push(c.cited_text)
    return q
  }, [data])
  // A citation points into the source register; open it first so the browser can scroll there.
  const openRegister = () => {
    if (register.current) register.current.open = true
  }

  return (
    <section className="ai-summary" aria-labelledby={`${id}-title`}>
      <h2 id={`${id}-title`} className="ai-h">
        {title}
      </h2>
      <p className="ai-mark">
        AI-generated by <span className="id">{data.model}</span> on {formatDate(data.generated)}, from the{' '}
        {data.sources.length} sources listed under it.
      </p>
      {data.reviewed ? (
        <p className="ai-review">
          <UserCheck size={18} aria-hidden="true" className="ai-review-yes" />
          <span>
            Reviewed by <strong>@{data.reviewed_by}</strong>, who checked it against those sources.
          </span>
        </p>
      ) : (
        <p className="ai-review">
          <TriangleAlert size={18} aria-hidden="true" className="ai-review-no" />
          <span>
            <strong>Not reviewed yet.</strong> No one has checked this text against its sources, so read it as a draft.
          </span>
        </p>
      )}
      {intro && <p className="ai-intro">{intro}</p>}
      <p className="ai-legend">
        <span className="ai-legend-source">White underlined text</span> is stated in a cited source; the number after it
        opens the source. <span className="ai-own">Lighter text without an underline</span> is the assistant's own
        explanation.
      </p>
      <div className="ai-text">
        {paragraphs(data.blocks).map((para, p) => (
          <p key={p}>
            {para.map((piece) =>
              piece.kind === 'source' ? (
                <Fragment key={piece.key}>
                  <span className="ai-said">{piece.text}</span>
                  {[...new Set(piece.citations.map((c) => index[c.source_id]))].map((n) => (
                    <a key={n} href={`#${id}-src-${n}`} className="ai-cite" aria-label={`Source ${n}`} onClick={openRegister}>
                      {n}
                    </a>
                  ))}
                </Fragment>
              ) : (
                <span key={piece.key} className="ai-own">
                  {piece.text}
                </span>
              ),
            )}
          </p>
        ))}
      </div>
      <details className="ai-register" ref={register}>
        <summary>
          Sources <span className="ai-count">{data.sources.length}</span>
        </summary>
        <ol className="ai-sources">
          {data.sources.map((source, i) => (
            <Source key={source.id} source={source} n={i + 1} id={id} quotes={quotes[source.id] ?? []} />
          ))}
        </ol>
      </details>
    </section>
  )
}
